export function getEncouragement(dateSeed: string): string {
  // 用日期做种子保证当天稳定
  let hash = 0;
  for (let i = 0; i < dateSeed.length; i++) {
    hash = ((hash << 5) - hash + dateSeed.charCodeAt(i)) | 0;
  }
  const idx = Math.abs(hash) % ENCORAGEMENTS.length;
  return ENCORAGEMENTS[idx];
}
